-- 4) wp_users_legacy: production has no UNIQUE constraint at all on
-- user_login/user_email (already dropped above). Its actual guarantee is
-- a PLAIN (non-unique) functional btree index on lower(user_email), used
-- for case-insensitive lookups, not deduplication. A UNIQUE version here
-- would reintroduce the exact invented-uniqueness risk Step 6 warned
-- against (import would fail on any case-duplicate email that production
-- itself accepts). Fixed in "fix round 1" — this was originally created
-- as a UNIQUE INDEX by mistake; it must stay plain.
CREATE INDEX "idx_wp_users_legacy_email" ON "wp_users_legacy" (lower(user_email));

-- 5) shelter_volunteers: production bumps `updated_at` via
-- set_timestamp_shelter_volunteers, a per-row BEFORE UPDATE trigger.
-- The generic set_updated_at() function already exists (created by the
-- init migration for users/shelters/volunteers) — reuse it here.
CREATE TRIGGER trg_shelter_volunteers_updated_at
  BEFORE UPDATE ON "shelter_volunteers"
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 6) deletion_flags: production's second index, a partial UNIQUE on
-- (table_name, record_id) WHERE status = 'pending' — enforces "at most
-- one pending deletion flag per record" without blocking historical
-- (already-deleted) flags for the same record. Not representable as a
-- Prisma @@unique (no WHERE clause support), so appended by hand.
CREATE UNIQUE INDEX "uq_deletion_flags_pending" ON "deletion_flags" ("table_name", "record_id") WHERE status = 'pending';
