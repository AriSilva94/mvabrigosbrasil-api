-- 1) shelter_history.id: the migration above (auto-generated by
-- `prisma migrate diff`) drops the DEFAULT gen_random_uuid() that the
-- init migration had hand-added, because Prisma's @default(uuid()) is a
-- client-side default. shelter_history is populated by the
-- log_shelter_changes() trigger, which never sets `id` itself, so the
-- DB-side default must be re-asserted or every trigger-inserted row
-- fails with a NOT NULL violation on `id`.
ALTER TABLE "shelter_history" ALTER COLUMN "id" SET DEFAULT gen_random_uuid();

